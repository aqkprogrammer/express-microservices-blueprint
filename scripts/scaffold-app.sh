#!/usr/bin/env bash
# Creates the boilerplate for a service workspace (package.json, tsconfig,
# prisma.config.ts). Used while building the blueprint; kept for adding services.
set -euo pipefail
name="$1"; description="$2"; with_prisma="${3:-yes}"
dir="apps/$name"
mkdir -p "$dir/src"
cat > "$dir/package.json" <<JSON
{
  "name": "@emb/$name",
  "version": "0.1.0",
  "private": true,
  "type": "module",
  "description": "$description",
  "scripts": {
    "build": "tsc -b",
    "start": "node --import ./dist/telemetry.js dist/main.js",
    "dev": "tsx watch --conditions=source --import ./src/telemetry.ts src/main.ts"
  },
  "dependencies": {}
}
JSON
cat > "$dir/tsconfig.json" <<JSON
{
  "extends": "../../tsconfig.base.json",
  "compilerOptions": { "rootDir": "src", "outDir": "dist", "tsBuildInfoFile": "dist/.tsbuildinfo" },
  "include": ["src"],
  "exclude": ["src/**/*.test.ts"],
  "references": [
    { "path": "../../packages/config" },
    { "path": "../../packages/contracts" },
    { "path": "../../packages/database" },
    { "path": "../../packages/http-kit" },
    { "path": "../../packages/logger" },
    { "path": "../../packages/messaging" },
    { "path": "../../packages/observability" },
    { "path": "../../packages/security" }
  ]
}
JSON
if [ "$with_prisma" = "yes" ]; then
  mkdir -p "$dir/prisma/migrations"
  cp apps/product-service/prisma.config.ts "$dir/prisma.config.ts"
  printf '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n' > "$dir/prisma/migrations/migration_lock.toml"
  (cd "$dir" && npm pkg set scripts.prisma:generate="prisma generate" scripts.prisma:migrate="prisma migrate deploy" scripts.db:seed="node dist/seed.js")
fi
